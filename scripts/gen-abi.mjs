// Writes the contract ABIs the TypeScript packages use from the Foundry build output.
import { readFileSync, writeFileSync } from "node:fs";

const out = (p) => JSON.parse(readFileSync(new URL(`../contracts/out/${p}`, import.meta.url))).abi;
const abis = {
  dealFactoryAbi: out("DealFactory.sol/DealFactory.json"),
  dealVaultAbi: out("DealVault.sol/DealVault.json"),
  identityRegistryAbi: out("IdentityRegistryUpgradeable.sol/IdentityRegistryUpgradeable.json"),
  reputationRegistryAbi: out("ReputationRegistryUpgradeable.sol/ReputationRegistryUpgradeable.json"),
  validationRegistryAbi: out("ValidationRegistryUpgradeable.sol/ValidationRegistryUpgradeable.json"),
};
let src = "// Generated by scripts/gen-abi.mjs from the Foundry build. Do not edit.\n";
for (const [name, abi] of Object.entries(abis)) src += `export const ${name} = ${JSON.stringify(abi)} as const;\n`;
writeFileSync(new URL("../packages/sdk/src/abi.ts", import.meta.url), src);
console.log("wrote packages/sdk/src/abi.ts");
